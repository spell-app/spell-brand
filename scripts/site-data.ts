/**
 * `yarn site:data [--check]` (in spell-brand):  the data of the brand's docs set, `docs/__data/`.
 * - Served at `/components/brand/__data/`, with the set's pages (epic `people-and-orgs` P18).
 * - `components.json5` (`SiteDataFile`):  every `<brand-*>` tag, from its vocabulary and sheet.
 *   Spell UI's own builder writes it, as a set's (`spell-ui/tools/SiteDataBuilder`, its `set`):
 *   - each tag's page is `<tag>.html`, beside the data's folder (the set's pages are ONE flat folder)
 *   - its topics are the set's groups, from `pages.json5` (the side column's groups, as Epic UI's)
 *   - `nav`:  the side column's own links and band titles, from `pages.json5`
 * - `pages.json5`:  HAND-KEPT.
 *   - Spell UI's per-family facts (title, summary, status);  a new family is seeded here, once
 *   - the set's own `groups` and `nav`, which this script keeps
 * - `search.json5` (`SiteSearchFile`):  every page's title and sections, read from the pages' markup.
 *   - by Spell UI's rules (`SiteSearchBuilder.page()`)
 *   - an element's page names its tag
 * - The editors' element descriptions, by Spell UI's `ElementManifests`:
 *   - `custom-elements.json`:  `package.json`'s `customElements`
 *   - `html-custom-data.json`:  VS Code's `html.customData`
 *   - `css-custom-data.json`:  VS Code's `css.customData`
 *   - VS Code's two are carried by spell-app's VS Code extension, copied when it's built:  one in every window
 * - Written through the kit's `writeOrCheck()`:  only what changed, keeping the comments in a `.json5` file.
 * - `--check`:  writes nothing;  exits 1 while any file is stale (`spell pack check brand` runs it).
 * - `spell pack build brand` runs it after the pack.
 *   Rerun it after changing a vocabulary, a sheet's tokens or a page's sections, and commit what it writes.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs"
import path from "node:path"

import { readJSON5File } from "spell/util/node/json5"
import { writeOrCheck } from "spell/element-tools/generatedFiles"
import { Terminal } from "spell/element-tools/Terminal"
import type {
  SiteDataFile,
  SitePagesFile,
  SiteSearchFile,
  SiteSet
} from "spell-ui/docs-components/docs-components.types"
import { ElementManifests } from "spell-ui/tools/ElementManifests"
import { SiteDataBuilder } from "spell-ui/tools/SiteDataBuilder"
import { SiteSearchBuilder } from "spell-ui/tools/SiteSearchBuilder"

/** This repo, spell-brand. */
const BRAND = path.resolve(import.meta.dirname, "..")

/** The set's pages, `docs/`, and its data, `docs/__data/`. */
const DOCS = path.join(BRAND, "docs")
const DATA = path.join(DOCS, "__data")

/** The set's home;  every other page in `docs/` is an element's, named for its tag. */
const HOME = "index.html"

/** `pages.json5`'s own comment:  what it holds, and who reads it. */
const PAGES_COMMENT =
  "HAND-KEPT facts of the brand's docs set, read by `yarn site:data` in spell-brand (scripts/site-data.ts), which " +
  "writes components.json5 and search.json5 beside this.  `families`:  Spell UI's per-family facts (title, summary, " +
  "status ...;  `SitePagesFile` in spell-ui/docs-components/docs-components.types), a new family seeded " +
  "here once.  `groups`:  the side column's groups, in order;  a tag no group names shows under Other.  `nav`:  the " +
  "side column's own links (`file` relative to the set's root, `/components/brand/`) and band titles (`SiteNav`)."

const isCheck = process.argv.includes("--check")
const own = readOwnFacts()
const builder = new SiteDataBuilder({
  components: path.join(BRAND, "src/components"),
  docs: false,
  data: DATA,
  set: own
})
const { data, pages } = await builder.build()
const setData: SiteDataFile = {
  ...data,
  $comment:
    "GENERATED by `yarn site:data` (spell-brand, scripts/site-data.ts) -- do not edit.  Shape:  `SiteDataFile` in " +
    "spell-ui/docs-components/docs-components.types;  hand-kept facts:  pages.json5 beside this."
}
const stale = writeOrCheck(
  [
    [builder.dataFile, SiteDataBuilder.stringify(setData)],
    [builder.pagesFile, SiteDataBuilder.stringify(pagesFile(pages, own))],
    [path.join(DATA, "search.json5"), SiteDataBuilder.stringify(search())],
    ...new ElementManifests({
      data: setData,
      packageFolder: BRAND,
      componentsPath: "src/components",
      readme:
        "Spell's brand elements (`brand-*`), a component pack on Spell UI.  Generated by `yarn site:data` -- do not edit."
    }).outputs(DATA)
  ],
  { command: "site:data", isCheck }
)
Terminal.out(
  `brand site data:  ${setData.components.length} tags in ${Object.keys(setData.families).length} families;  ` +
    (stale.length ? `${stale.length} file${stale.length === 1 ? "" : "s"} ${isCheck ? "stale" : "written"}` : "current")
)

/** `pages.json5` as kept:  Spell UI's facts (a new family seeded), then the set's own. */
function pagesFile(pages: SitePagesFile, own: SiteSet): SitePagesFile & SiteSet {
  return { ...pages, $comment: PAGES_COMMENT, ...own }
}

/** `search.json5`:  the home first, then each element page A-Z, each naming its tag. */
function search(): SiteSearchFile {
  const pages = existsSync(DOCS) ? readdirSync(DOCS).filter((file) => file.endsWith(".html") && file !== HOME) : []
  const files = [...(existsSync(path.join(DOCS, HOME)) ? [HOME] : []), ...pages.sort()]
  return {
    $comment:
      "GENERATED by `yarn site:data` (spell-brand, scripts/site-data.ts) from the set's pages -- do not edit.  " +
      "Shape:  `SiteSearchFile` in spell-ui/docs-components/docs-components.types.",
    pages: files.map((file) => {
      const page = SiteSearchBuilder.page(file, readFileSync(path.join(DOCS, file), "utf8"))
      return file === HOME ? page : { ...page, tag: file.replace(/\.html$/, "") }
    })
  }
}

/** The set's own hand-kept facts in `pages.json5`, which Spell UI's builder doesn't keep:  `groups` and `nav`. */
function readOwnFacts(): SiteSet {
  const file = readJSON5File<Partial<SiteSet>>(path.join(DATA, "pages.json5"))
  if (!file.groups || !file.nav) {
    throw new TypeError("site-data:  docs/__data/pages.json5 has no `groups` or `nav`;  add them (see Epic UI's)")
  }
  return { groups: file.groups, nav: file.nav }
}
